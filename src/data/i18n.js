export function getCopy(language) {
  return translations[language] ?? translations[defaultLanguage];
}

export function languagePath(language, slug = '') {
  return `/${language}/${slug ? `${slug}/` : ''}`;
}

export function getNavItems(language) {
  const copy = getCopy(language);

  return [
    { slug: '', label: copy.nav.home, href: languagePath(language) },
    ...pageSlugs.map((slug) => ({
      slug,
      label: copy.nav[slug],
      href: languagePath(language, slug)
    }))
  ];
}
